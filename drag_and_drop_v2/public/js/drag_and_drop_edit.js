                            for (var row = 0; row < rows; row++) {
                                for (var col = 0; col < cols; col++) {
                                    zones.push({
                                        width: zone_width,
                                        height: zone_height,
                                        x: (padding * (col + 1) + (col * zone_width)),
                                        y: (padding * (row + 1) + (row * zone_height))
                                    });
                                }
                            }

                            return {
                                width: width,
                                height: height,
                                zones: zones
                            };
